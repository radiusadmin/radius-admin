def _write(path, text, mode=0o755):
    with open(path, "w") as fh:
        fh.write(text)
    os.chmod(path, mode)


class Env:
    def __init__(self, root):
        self.root = root
        self.raddb = os.path.join(root, "raddb")
        self.staging = os.path.join(root, "staging")
        self.work = os.path.join(root, "work")
        self.conf = os.path.join(root, "helper.conf")
        self.stager = pwd.getpwnam(STAGER)
        self.freerad = pwd.getpwnam(FREERAD)

    # ---- helpers
    def stage(self, policy=GOOD_POLICY, clients=GOOD_CLIENTS):
        for name, data in (("policy", policy), ("clients", clients)):
            p = os.path.join(self.staging, name)
            if os.path.lexists(p):
                os.unlink(p)
            with open(p, "wb") as fh:
                fh.write(data)
            os.chown(p, self.stager.pw_uid, self.stager.pw_gid)
            os.chmod(p, 0o600)

    def call(self, req, raw=None):
        a, b = socket.socketpair(socket.AF_UNIX, socket.SOCK_STREAM)
        try:
            p = subprocess.Popen([PYTHON, "-I", HELPER, "--config", self.conf], stdin=b,
                                 stdout=subprocess.DEVNULL, stderr=subprocess.PIPE)
            b.close()
            a.sendall(raw if raw is not None else (json.dumps(req) + "\n").encode())
            buf = b""
            while True:
                c = a.recv(65536)
                if not c:
                    break
                buf += c
            p.wait(timeout=120)
            assert p.returncode == 0, p.stderr.read()
        finally:
            a.close()
        assert buf.endswith(b"\n") and buf.count(b"\n") == 1
        return json.loads(buf)

    def live(self, name):
        p = (os.path.join(self.raddb, "policy.d", "radius-admin") if name == "policy"
             else os.path.join(self.raddb, "radius-admin-clients.conf"))
        with open(p, "rb") as fh:
            return fh.read()


