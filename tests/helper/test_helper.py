def test_rollback_roundtrip_and_pruning(env):
    ids = []
    for i in range(5):
        env.stage(policy=GOOD_POLICY + b"# v%d\n" % i)
        r = env.call({"action": "apply"})
        assert r["ok"], r
        ids.append(r["backup_id"])
    s = env.call({"action": "status"})
    assert len(s["backups"]) == 3  # keep_backups = 3
    assert s["backups"] == sorted(s["backups"], reverse=True)
    target = s["backups"][0]  # holds v3 (the state before v4 was applied)
    r = env.call({"action": "rollback", "backup_id": target})
    assert r["ok"] is True, r
    assert r["restored"] == target
    assert env.live("policy") == GOOD_POLICY + b"# v3\n"
    s = env.call({"action": "status"})
    assert s["last_apply"]["action"] == "rollback"


