def test_apply_success(env):
    env.stage()
    r = env.call({"action": "apply"})
    assert r["ok"] is True, r
    assert r["rolled_back"] is False
    assert r["policy_sha256"] == hashlib.sha256(GOOD_POLICY).hexdigest()
    assert r["clients_sha256"] == hashlib.sha256(GOOD_CLIENTS).hexdigest()
    assert env.live("policy") == GOOD_POLICY and env.live("clients") == GOOD_CLIENTS
    for name in ("policy", "clients"):
        p = (os.path.join(env.raddb, "policy.d", "radius-admin") if name == "policy"
             else os.path.join(env.raddb, "radius-admin-clients.conf"))
        st = os.stat(p)
        assert stat.S_IMODE(st.st_mode) == 0o640
        assert st.st_uid == 0 and st.st_gid == env.freerad.pw_gid
    # no stray temp files in policy.d (radiusd would $INCLUDE them)
    assert sorted(os.listdir(os.path.join(env.raddb, "policy.d"))) == ["radius-admin"]
    bdir = os.path.join(env.work, "backups", r["backup_id"])
    assert open(os.path.join(bdir, "policy"), "rb").read() == b"# old policy\n"
    assert stat.S_IMODE(os.stat(bdir).st_mode) == 0o700
    s = env.call({"action": "status"})
    assert s["last_apply"]["backup_id"] == r["backup_id"]
    assert s["last_apply"]["policy_sha256"] == r["policy_sha256"]
    assert s["backups"] == [r["backup_id"]]
    assert "systemctl restart freeradius" in open(os.path.join(env.root, "systemctl.log")).read()


