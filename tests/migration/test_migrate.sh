#!/bin/bash
# Test deploy/migrate_sqlite_to_pg.py against a throwaway PostgreSQL database loaded from
# sql/10,20,30 and a SQLite DB built from the stock FreeRADIUS 3.2.10 sqlite schema.
# Run as root in a sandbox with PostgreSQL 16 and roles from sql/00-roles.sql.
# Usage: test_migrate.sh <stock sqlite schema.sql> <workdir> [python]
set -euo pipefail
SCHEMA=${1:?sqlite schema.sql}; W=${2:?workdir}; PY=${3:-/usr/bin/python3.12}
HERE=$(cd "$(dirname "$0")" && pwd); ROOT=$(cd "$HERE/../.." && pwd)
DB=radius_migtest
rm -rf "$W"; mkdir -p "$W/raddb"; chmod 755 "$W"
fail() { echo "FAIL: $*"; exit 1; }
pass() { echo "PASS: $*"; }
psqlp() { runuser -u postgres -- psql -X -q -t -A -v ON_ERROR_STOP=1 "$@"; }

# ---- fresh target DB
psqlp -d postgres -c "DROP DATABASE IF EXISTS $DB" -c "CREATE DATABASE $DB OWNER radius_owner"
for f in 10-freeradius-schema.sql 20-radius-admin-schema.sql 30-grants.sql; do
  psqlp -d $DB -f "$ROOT/sql/$f" >/dev/null
done
DSN="dbname=$DB host=/var/run/postgresql user=postgres"

# ---- source SQLite
sqlite3 "$W/freeradius.db" < "$SCHEMA"
PW_LEAK='CleartextLeak-Pa55w0rd!'
sqlite3 "$W/freeradius.db" <<SQL
INSERT INTO radcheck (username, attribute, op, value) VALUES
 ('alice','Crypt-Password',':=','\$6\$saltsalt\$abcdefghijklmnopqrstuvwxyz'),
 ('bob','Crypt-Password',':=','\$6\$saltsal2\$zyxwvutsrqponmlkjihgfedcba'),
 ('carol','Crypt-Password',':=','\$6\$saltsal3\$0123456789abcdefghijklmnop');
DELETE FROM radcheck WHERE username='bob';
INSERT INTO radcheck (username, attribute, op, value) VALUES ('bob','Crypt-Password',':=','\$6\$x\$y');
INSERT INTO radusergroup (username, groupname, priority) VALUES ('alice','net-admins',1),('bob','net-admins',1),('carol','net-admins',1);
INSERT INTO radreply (username, attribute, op, value) VALUES ('alice','Reply-Message','=','hi');
INSERT INTO radgroupcheck (groupname, attribute, op, value) VALUES ('net-admins','Auth-Type',':=','PAP');
INSERT INTO radgroupreply (groupname, attribute, op, value) VALUES ('net-admins','Service-Type',':=','Administrative-User');
INSERT INTO nas (nasname, shortname, type, secret, description) VALUES ('10.9.9.9', NULL, 'other', 'nas-secret-xyz', 'legacy');
INSERT INTO radpostauth (username, pass, reply, authdate, class) VALUES
 ('alice','$PW_LEAK','Access-Accept','2026-10-01 12:00:00.123456', NULL),
 ('bob','$PW_LEAK','Access-Reject','2026-10-01 12:01:00.000001', 'c1'),
 ('host/pc1.example.net','','Access-Accept','2026-10-02 08:00:00.5', NULL);
INSERT INTO radacct (acctsessionid, acctuniqueid, username, nasipaddress, nasporttype, acctstarttime, acctupdatetime,
  acctstoptime, acctsessiontime, calledstationid, callingstationid, acctterminatecause, framedipaddress)
 VALUES ('s1','u1','alice','192.0.2.5','Virtual',1790000000,1790000060,1790000120,120,'','192.0.2.200','User-Request',''),
        ('s2','u2','host/pc1','192.0.2.6','Ethernet',1790000000,NULL,NULL,NULL,'','AA-BB','','10.20.0.5');
SQL

# ---- clients.conf + switches.conf mirroring the production ones (fake secrets)
cat > "$W/raddb/clients.conf" <<'CONF'
#  -*- text -*-
##  clients.conf -- client configuration directives
$INCLUDE switches.conf
client wifi-aps {
        ipaddr = 203.0.113.201
        secret = WifiApSecret-0123456789abcdef
        require_message_authenticator = yes
}
client localhost {
    ipaddr = 127.0.0.1
    secret = testing123
    require_message_authenticator = auto
}
client localhost_ipv6 {
	ipv6addr	= ::1
	secret		= testing123
}
CONF
{
  echo "# generated by a site script"
  for n in $(seq 1 25); do
    printf 'client sw-192-0-2-%d {\n\tipv4addr = 192.0.2.%d\n\tsecret = "Sw%02dSecret-%s"\n\tshortname = sw-192-0-2-%d\n}\n\n' \
      "$n" "$n" "$n" "$(printf '%020d' $n)" "$n"
  done
} > "$W/raddb/switches.conf"
chmod -R a+rX "$W"

M="$PY $ROOT/deploy/migrate_sqlite_to_pg.py --sqlite $W/freeradius.db --raddb $W/raddb --dsn"

# 1. dry run changes nothing and prints no secrets
OUT=$($M "$DSN" --dry-run 2>&1) || { echo "$OUT"; fail "dry run"; }
echo "$OUT" | grep -q "DRY RUN" || fail "dry run banner"
[ "$(psqlp -d $DB -c 'SELECT count(*) FROM radcheck')" = 0 ] || fail "dry run wrote data"
pass "dry run rolled back"

# 2. real run
OUT=$($M "$DSN" 2>&1) || { echo "$OUT"; fail "migration failed"; }
echo "$OUT"
for s in WifiApSecret Sw01Secret Sw25Secret testing123 nas-secret-xyz "$PW_LEAK"; do
  echo "$OUT" | grep -qF -- "$s" && fail "secret/password printed: $s"
done
pass "no secrets or passwords in output"

q() { psqlp -d $DB -c "$1"; }
[ "$(q 'SELECT count(*) FROM radcheck')" = 3 ] || fail radcheck
[ "$(q "SELECT value FROM radcheck WHERE username='alice'")" = '$6$saltsalt$abcdefghijklmnopqrstuvwxyz' ] || fail "radcheck value"
[ "$(q 'SELECT max(id) FROM radcheck')" = 4 ] || fail "radcheck ids preserved"
NEXT=$(q "INSERT INTO radcheck (username, attribute, op, value) VALUES ('z','Auth-Type',':=','Reject') RETURNING id")
[ "$NEXT" = 5 ] || fail "radcheck sequence not fixed (next id $NEXT)"
pass "radcheck copied, ids preserved, sequence fixed"
[ "$(q 'SELECT count(*) FROM radusergroup')" = 3 ] || fail radusergroup
[ "$(q 'SELECT count(*) FROM radreply')" = 1 ] || fail radreply
[ "$(q 'SELECT count(*) FROM radgroupcheck')" = 1 ] || fail radgroupcheck
[ "$(q 'SELECT count(*) FROM radgroupreply')" = 1 ] || fail radgroupreply
[ "$(q 'SELECT shortname FROM nas')" = 10.9.9.9 ] || fail "nas shortname fallback"
pass "radreply/radgroup*/radusergroup/nas copied"
[ "$(q 'SELECT count(*) FROM radpostauth')" = 3 ] || fail radpostauth
q "SELECT t::text FROM radpostauth t" | grep -qF -- "$PW_LEAK" && fail "password copied into radpostauth"
q "SELECT column_name FROM information_schema.columns WHERE table_name='radpostauth'" | grep -qx pass && fail "pass column"
[ "$(q "SELECT to_char(authdate AT TIME ZONE 'UTC', 'YYYY-MM-DD') FROM radpostauth WHERE username='alice'")" = 2026-10-01 ] || fail "authdate"
[ "$(q "SELECT class FROM radpostauth WHERE username='bob'")" = c1 ] || fail "class"
runuser -u postgres -- psql -X -q -t -A -v ON_ERROR_STOP=1 -d $DB -c "SET ROLE radius_fr; INSERT INTO radpostauth (username) VALUES ('x')"
NEXT=$(q "SELECT id FROM radpostauth WHERE username='x'")
[ "$NEXT" = 4 ] || fail "radpostauth sequence not fixed / radius_fr cannot insert (got $NEXT)"
pass "radpostauth history copied WITHOUT pass; sequence fixed; radius_fr can insert"
[ "$(q 'SELECT count(*) FROM radacct')" = 2 ] || fail radacct
[ "$(q "SELECT acctsessiontime||' '||host(nasipaddress)||' '||coalesce(host(framedipaddress),'-')||' '||extract(epoch from acctstarttime)::bigint FROM radacct WHERE acctuniqueid='u1'")" = "120 192.0.2.5 - 1790000000" ] || fail "radacct conversion"
[ "$(q "SELECT acctstoptime IS NULL FROM radacct WHERE acctuniqueid='u2'")" = t ] || fail "radacct null stop"
pass "radacct copied with epoch->timestamptz and ''->NULL inet"
[ "$(q 'SELECT count(*) FROM ui.radius_client')" = 26 ] || fail "client count"
[ "$(q "SELECT ipaddr||' '||require_ma||' '||limit_proxy_state FROM ui.radius_client WHERE name='wifi-aps'")" = "203.0.113.201 yes auto" ] || fail wifi-aps
[ "$(q "SELECT ipaddr||' '||require_ma||' '||secret FROM ui.radius_client WHERE name='sw-192-0-2-7'")" = "192.0.2.7 auto Sw07Secret-00000000000000000007" ] || fail "switch 7"
[ "$(q "SELECT count(*) FROM ui.radius_client WHERE name LIKE 'localhost%'")" = 0 ] || fail "localhost imported"
pass "clients.conf + switches.conf imported (26), localhost skipped"
[ "$(q "SELECT string_agg(priority||':'||connection||':'||coalesce(ssid,'-')||':'||ad_group||':'||vlan, ',' ORDER BY id) FROM ui.access_rule")" = \
  "10:wired:-:Wired-Support:510,20:wired:-:Wired-Office:500,30:wired:-:Wired-Utility:520,10:wireless:Example_Main_Test:Wireless-Office-Test:530,10:wireless:Example_Admin:WIRELESS-SUPPORT:510,10:wireless:Example_Main:WIRELESS-OFFICE:530" ] || fail "seed rules"
[ "$(q "SELECT value FROM ui.setting WHERE key='admin_priv15'")" = false ] || fail "settings"
pass "seed access rules + settings"

# 3. render the migrated rules/clients with unlang.py and check -XC-relevant content
runuser -u postgres -- $PY - "$ROOT" "$DB" <<'PY'
import sys; sys.path.insert(0, sys.argv[1] + "/app")
import psycopg2, psycopg2.extras
from radius_admin import unlang
c = psycopg2.connect("dbname=%s host=/var/run/postgresql user=postgres" % sys.argv[2])
cur = c.cursor(cursor_factory=psycopg2.extras.RealDictCursor)
cur.execute("SELECT * FROM ui.access_rule"); rules = cur.fetchall()
cur.execute("SELECT * FROM ui.radius_client"); clients = cur.fetchall()
for r in rules:  # migrated rules pass the UI validators
    unlang.validate_ad_group(r["ad_group"]); unlang.validate_vlan(r["vlan"])
    if r["ssid"] is not None: unlang.validate_ssid(r["ssid"])
p = unlang.render_policy("")
t = unlang.render_clients(clients)
assert "radius_admin_vlan_rule_hex(" in p
assert t.count("\nclient ") == 26 and "require_message_authenticator = yes" in t
print("PASS: migrated rules validate; policy + 26 clients render")
PY

# 4. second run refuses (tables not empty); --force replaces
$M "$DSN" > "$W/second.out" 2>&1 && fail "second run should refuse"
grep -q "refusing" "$W/second.out" || fail "refusal message"
[ "$(q 'SELECT count(*) FROM radcheck')" = 4 ] || fail "refused run changed data"
pass "second run refused without --force"
$M "$DSN" --force > "$W/force.out" 2>&1 || { cat "$W/force.out"; fail "--force run"; }
[ "$(q 'SELECT count(*) FROM radcheck')" = 3 ] || fail "--force did not replace"
[ "$(q 'SELECT count(*) FROM ui.access_rule')" = 6 ] || fail "--force duplicated seed rules"
pass "--force replaces data, seed rules not duplicated"

# 5. bad input aborts the whole transaction
psqlp -d $DB -c "DELETE FROM radcheck; DELETE FROM radusergroup; DELETE FROM radreply; DELETE FROM radgroupcheck; DELETE FROM radgroupreply; DELETE FROM nas; DELETE FROM radacct; DELETE FROM radpostauth; DELETE FROM ui.radius_client"
printf 'client bad {\n\tipaddr = 10.1.1.1\n\tsecret = "has space"\n}\n' >> "$W/raddb/switches.conf"
$M "$DSN" > "$W/bad.out" 2>&1 && fail "bad secret should abort"
grep -q "client bad" "$W/bad.out" || fail "bad secret message"
grep -q "has space" "$W/bad.out" && fail "bad secret printed"
[ "$(q 'SELECT count(*) FROM radcheck')" = 0 ] || fail "partial write after abort"
pass "invalid client aborts with nothing written and secret not printed"

psqlp -d postgres -c "DROP DATABASE $DB"
echo "ALL MIGRATION TESTS PASSED"
