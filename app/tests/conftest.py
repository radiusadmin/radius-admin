class FakeHelper:
    """Unix-socket server speaking the SPEC section 6 protocol."""

    def __init__(self, path, staging):
        self.path = path
        self.staging = staging
        self.requests = []
        self.fail_next = {}
        self.backups = []
        self._sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        self._sock.bind(path)
        self._sock.listen(8)
        self._stop = False
        self._t = threading.Thread(target=self._serve, daemon=True)
        self._t.start()

    def _serve(self):
        while not self._stop:
            try:
                conn, _ = self._sock.accept()
            except OSError:
                return
            with conn:
                buf = b""
                while b"\n" not in buf:
                    chunk = conn.recv(65536)
                    if not chunk:
                        break
                    buf += chunk
                try:
                    req = json.loads(buf.split(b"\n")[0])
                except ValueError:
                    conn.sendall(b'{"ok":false,"action":"","message":"bad json"}\n')
                    continue
                self.requests.append(req)
                conn.sendall((json.dumps(self.handle(req)) + "\n").encode())

    def _staged(self):
        import hashlib
        out = {}
        for n in ("policy", "clients"):
            with open(os.path.join(self.staging, n), "rb") as fh:
                out[n] = hashlib.sha256(fh.read()).hexdigest()
        return out

    def handle(self, req):
        a = req.get("action")
        if a in self.fail_next:
            resp = dict(self.fail_next.pop(a))
            resp.setdefault("ok", False)
            resp.setdefault("action", a)
            return resp
        if a == "status":
            return {"ok": True, "action": a, "message": "", "service_active": True, "listening": True,
                    "fips_enabled": False,
                    "radiusd_version": "FreeRADIUS Version 3.2.10 (fake)", "last_apply": None,
                    "backups": list(reversed(self.backups))[:20]}
        if a == "validate":
            h = self._staged()
            return {"ok": True, "action": a, "message": "Configuration appears to be OK",
                    "output": "radiusd: #### Skipping IP addresses and Ports ####\nConfiguration appears to be OK"}
        if a == "apply":
            h = self._staged()
            bid = "20261023T%06dZ" % (100000 + len(self.backups))
            self.backups.append(bid)
            return {"ok": True, "action": a, "message": "applied; freeradius active", "backup_id": bid,
                    "policy_sha256": h["policy"], "clients_sha256": h["clients"]}
        if a == "rollback":
            if req.get("backup_id") not in self.backups:
                return {"ok": False, "action": a, "message": "no such backup"}
            return {"ok": True, "action": a, "message": "rolled back", "backup_id": req["backup_id"]}
        return {"ok": False, "action": a or "", "message": "unknown action"}

    def close(self):
        self._stop = True
        self._sock.close()


