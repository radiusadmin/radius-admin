def _install_unlang_stub():
    """Only used when the FR engineer's radius_admin/unlang.py is not importable."""
    import ipaddress
    import hashlib

    mod = types.ModuleType("radius_admin.unlang")
    mod.IS_TEST_STUB = True

    def sha256_hex(text):
        return hashlib.sha256(text.encode()).hexdigest()

    def _re(pat, v, msg):
        if not isinstance(v, str) or not re.fullmatch(pat, v):
            raise ValueError(msg)
        return v

    mod.sha256_hex = sha256_hex
    mod.validate_ssid = lambda v: _re(r"[A-Za-z0-9 _.\-]{1,32}", v, "Invalid SSID.")
    mod.validate_ad_group = lambda v: _re(r"[A-Za-z0-9 _.()&\-]{1,64}", v, "Invalid AD group.")
    mod.validate_client_name = lambda v: _re(r"[A-Za-z0-9._-]{1,63}", v, "Invalid client name.")

    def validate_vlan(v):
        try:
            n = int(v)
        except (TypeError, ValueError):
            raise ValueError("VLAN must be a number 1-4094.") from None
        if not 1 <= n <= 4094:
            raise ValueError("VLAN must be a number 1-4094.")
        return n

    def validate_mac(v):
        h = re.sub(r"[-:.]", "", v or "")
        if not re.fullmatch(r"[0-9A-Fa-f]{12}", h):
            raise ValueError("Invalid MAC address.")
        h = h.upper()
        return "-".join(h[i:i + 2] for i in range(0, 12, 2))

    def validate_ipaddr(v):
        try:
            if "/" in v:
                return str(ipaddress.ip_network(v, strict=True))
            return str(ipaddress.ip_address(v))
        except ValueError:
            raise ValueError("Invalid IP address or network.") from None

    def validate_secret(v):
        if not re.fullmatch(r"[\x21-\x7e]{16,128}", v or "") or '"' in v or "\\" in v:
            raise ValueError("Secret must be 16-128 printable characters without quotes or backslashes.")
        return v

    def validate_custom_policy(v):
        if len(v.encode()) > 65536:
            raise ValueError("Too long.")
        for bad in ("$INCLUDE", "$-INCLUDE", "$ENV", "$TEMPLATE", "%{exec:", "Exec-Program", "`", "perl", "python"):
            if bad in v:
                raise ValueError("Forbidden construct: %s" % bad)
        if v.count("{") != v.count("}"):
            raise ValueError("Unbalanced braces.")
        return v

    def render_policy(custom):
        """SPEC section 10 signature: depends only on the custom policy body."""
        out = ["# generated by radius-admin (test stub) - do not edit",
               "policy radius_admin_postauth { %{sql:SELECT radius_admin_vlan_hex(...)} }",
               "radius_admin_custom {", custom or "\tnoop", "}"]
        return "\n".join(out) + "\n"

    def render_clients(clients):
        out = []
        for c in sorted((c for c in clients if c["enabled"]), key=lambda c: c["name"]):
            fam = "ipv6addr" if ":" in c["ipaddr"] else "ipv4addr"
            out.append('client %s {\n\t%s = %s\n\tsecret = "%s"\n\tshortname = %s\n\tnas_type = %s\n'
                       '\trequire_message_authenticator = %s\n\tlimit_proxy_state = %s\n}\n'
                       % (c["name"], fam, c["ipaddr"], c["secret"], c["name"], c["nas_type"],
                          c["require_ma"], c["limit_proxy_state"]))
        return "".join(out)

    for name, fn in list(locals().items()):
        if name.startswith(("validate_", "render_")):
            setattr(mod, name, fn)
    import radius_admin
    sys.modules["radius_admin.unlang"] = mod
    radius_admin.unlang = mod
    return mod


def _real_unlang_usable():
    """The real module must exist and have the SPEC section 10 signature
    render_policy(custom). RADIUS_ADMIN_TEST_UNLANG_STUB=1 forces the stub."""
    if os.environ.get("RADIUS_ADMIN_TEST_UNLANG_STUB") == "1":
        return False
    try:
        import inspect
        import radius_admin.unlang as real
    except ImportError:
        return False
    params = list(inspect.signature(real.render_policy).parameters)
    return params[:1] == ["custom"] and len([p for p in inspect.signature(real.render_policy).parameters.values()
                                             if p.default is inspect.Parameter.empty]) <= 1


