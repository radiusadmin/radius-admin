CSRF_RE = re.compile(r'name="csrf_token" value="([^"]+)"')


class Browser:
    def __init__(self, app, ip="192.0.2.50"):
        self.app = app
        self.c = app.test_client()
        self.ip = ip

    def _h(self, extra=None, origin=True):
        h = {"X-Real-IP": self.ip}
        if origin:
            h["Origin"] = ORIGIN
        h.update(extra or {})
        return h

    def get(self, path, headers=None, **kw):
        return self.c.get(path, base_url=BASE_URL, headers=self._h(headers, origin=False), **kw)

    def csrf_from(self, path, headers=None):
        r = self.get(path, headers=headers)
        m = CSRF_RE.search(r.get_data(as_text=True))
        assert m, "no csrf token on %s (status %s)" % (path, r.status_code)
        return m.group(1)

    def post(self, path, data=None, csrf=None, csrf_page=None, headers=None, origin=True, **kw):
        data = dict(data or {})
        if csrf is None:
            csrf = self.csrf_from(csrf_page or path, headers=headers)
        if csrf is not False:
            data["csrf_token"] = csrf
        return self.c.post(path, base_url=BASE_URL, data=data, headers=self._h(headers, origin=origin), **kw)

    def text(self, r):
        return r.get_data(as_text=True)


