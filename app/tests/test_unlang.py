"""Tests for radius_admin.unlang (pure functions, no database needed).

Semantics of the generated unlang were verified against a real FreeRADIUS 3.2.10
(--enable-fips-workaround) by tests/freeradius/run-tests.py; these tests pin the
rendering contract and the validators.
"""
import os
import re
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from radius_admin import unlang  # noqa: E402
from radius_admin.unlang import PolicyInputError  # noqa: E402


def render(custom=""):
    return unlang.render_policy(custom)


# ------------------------------------------------------------------ policy rendering
def test_policy_names_and_header():
    p = render()
    assert p.startswith("#\n#  Generated by radius-admin. DO NOT EDIT.")
    for name in ("radius_admin_mab {", "radius_admin_postauth {", "radius_admin_custom {"):
        assert ("\n" + name) in p
    assert re.search(r"\d{4}-\d{2}-\d{2}", p) is None  # no timestamp


def test_deterministic_and_only_custom_varies():
    a = render()
    assert a == render() == unlang.render_policy(None)
    assert unlang.sha256_hex(a) == unlang.sha256_hex(render())
    assert len(unlang.sha256_hex(a)) == 64
    b = render("noop\n")
    assert a != b
    assert a.split("radius_admin_custom {")[0] == b.split("radius_admin_custom {")[0]


def test_no_rules_or_settings_rendered():
    p = render()
    for word in ("Wired-Support", "Example_", "192.0.2", "LDAP-Group =="):
        assert word not in p
    with pytest.raises(TypeError):
        unlang.render_policy({"admin_subnet": "192.0.2.0/24"}, [], "")


def _sql_calls(p):
    return re.findall(r"%\{sql:(SELECT [^\n]*?)\}\"", p)


def test_sql_arguments_are_hex_or_constant_only():
    """Request/directory data reaches %{sql:...} only as hex-validated control
    attributes (FreeRADIUS un-escapes %{sql:} arguments after SQL escaping)."""
    p = render()
    calls = _sql_calls(p)
    assert len(calls) == 4
    allowed = {
        # %{hex:...} output is [0-9a-f] only; Tmp-String-5 is checked against hex below
        "SELECT radius_admin_mab_hex('%{control:Tmp-String-2}', '%{hex:NAS-IP-Address}', "
        "'%{control:Tmp-String-5}')",
        "SELECT radius_admin_admin_source_ok_hex('%{control:Tmp-String-4}')",
        "SELECT radius_admin_priv15()",
        "SELECT radius_admin_vlan_rule_hex(%{control:Tmp-String-7}, '%{control:Tmp-String-8}', "
        "'%{control:Tmp-String-3}')",
    }
    assert set(calls) == allowed
    for name in ("radius_admin_vlan(", "radius_admin_admin_source_ok(", "FROM mab_device"):
        assert name not in p.replace("radius_admin_vlan_rule_hex(", "").replace("radius_admin_admin_source_ok_hex(", "")
    # every interpolated value is validated against a hex/constant pattern before use
    assert "&control:Tmp-String-4 =~ /^[0-9a-f]{8}$|^([0-9a-f]{2}){2,64}$/" in p
    assert '"%{control:Tmp-String-3}" =~ /^(,[0-9a-f]+)*$/' in p
    assert '"%{control:Tmp-String-8}" =~ /^([0-9a-f]{2})*$/' in p
    assert '&Tmp-String-7 := "true"' in p and '&Tmp-String-7 := "false"' in p
    assert '&Tmp-String-5 := "%{hex:NAS-Port-Id}"' in p
    assert '"%{control:Tmp-String-5}" !~ /^([0-9a-f]{2})*$/' in p
    # MAB: Tmp-String-2 is built from regex captures of [0-9a-f]{2} only
    assert "&Tmp-String-2 := \"%{toupper:%{1}-%{2}-%{3}-%{4}-%{5}-%{6}}\"" in p


def test_eap_branch_uses_live_vlan_function():
    p = render()
    eap = p[p.index("# 802.1X EAP-TLS"):p.index("\n\tradius_admin_custom")]
    assert eap.index("if (!&TLS-Client-Cert-Subject-Alt-Name-Dns) {") < eap.index("ldap.authorize")
    nosan = eap[eap.index("if (!&TLS-Client-Cert-Subject-Alt-Name-Dns) {"):eap.index("ldap.authorize")]
    assert "\t\t\treject\n" in nosan and "no DNS name" in nosan
    assert "&Tmp-String-9 += &control:LDAP-Group[*]" in eap  # raw copy, no string re-parse
    assert "%{hex:control:Tmp-String-9[0]}" in eap
    assert '&Tmp-String-8 := "%{hex:Called-Station-Id}"' in eap
    assert "&control:Tmp-String-0 =~ /^[0-9]{1,4}$/" in eap
    assert "&Tunnel-Private-Group-Id := &control:Tmp-String-0" in eap
    # '<vlan>:<rule id>' is split by regex; anything else clears the VLAN (reject)
    assert "&control:Tmp-String-0 =~ /^([0-9]{1,4}):([0-9]{1,10})$/" in eap
    assert '&Tmp-String-6 := "%{2}"' in eap
    assert "no enabled access rule matches" in eap
    assert eap.rstrip().endswith("\t\t\treject\n\t\t}\n\t}")


def test_admin_branch_uses_live_settings():
    p = render()
    adm = p[p.index("# Switch/device admin logins"):p.index("# 802.1X EAP-TLS")]
    assert "%{hex:control:Tmp-IP-Address-0}" in adm
    assert "&Tmp-String-8 := \"%{sql:SELECT radius_admin_admin_source_ok_hex('%{control:Tmp-String-4}')}\"" in adm
    assert '&Tmp-String-8 := "f"' in adm          # default: fail closed
    assert '&control:Tmp-String-8 != "t"' in adm
    assert 'SQL-Group == "net-admins"' in adm
    assert "outside the management subnet" in adm and "not in group net-admins" in adm
    assert "\"%{sql:SELECT radius_admin_priv15()}\" == \"t\"" in adm
    assert '&Cisco-AVPair += "shell:priv-lvl=15"' in adm
    assert adm.count("\t\t\treject\n") == 2      # wrong source, not a switch admin


def test_authmethod_markers():
    p = render()
    for m in ('"mab"', '"pap-admin"', '"eap-tls"'):
        assert "&Tmp-String-1 := %s" % m in p


def test_mab_policy_shape():
    p = render()
    mab = p[p.index("radius_admin_mab {"):p.index("radius_admin_postauth {")]
    assert "!&EAP-Message" in mab and "&NAS-Port-Type == Ethernet" in mab
    assert ("%{sql:SELECT radius_admin_mab_hex('%{control:Tmp-String-2}', '%{hex:NAS-IP-Address}', "
            "'%{control:Tmp-String-5}')}" in mab)
    for word in ("expired", "disabled", "approval queue"):
        assert word in mab
    assert "&Auth-Type := Accept" in mab
    assert "Calling-Station-Id" in mab
    rx = re.search(r"=~ /\^(.*?)\$/i", mab).group(1)
    for ok in ("aabbccddeeff", "AA-BB-CC-DD-EE-FF", "aabb.ccdd.eeff", "aa:bb:cc:dd:ee:ff"):
        assert re.fullmatch(rx, ok, re.I)
        assert unlang.validate_mac(ok) == "AA-BB-CC-DD-EE-FF"
    for bad in ("aabbccddeef", "aabbccddeeff0", "gg:bb:cc:dd:ee:ff", "aa bb cc dd ee ff"):
        assert not re.fullmatch(rx, bad, re.I)


