# ------------------------------------------------------------------ custom policy
def test_custom_policy_verbatim_and_empty():
    assert "radius_admin_custom {\n\tnoop\n}" in render()
    assert "radius_admin_custom {\n\tnoop\n}" in render("   \n")
    body = '\tif (&User-Name == "x") {\n\t\tupdate reply {\n\t\t\t&Reply-Message := "hi"\n\t\t}\n\t}\n'
    p = render(custom=body)
    assert "radius_admin_custom {\n" + body + "}\n" in p
    assert p.endswith("}\n")


