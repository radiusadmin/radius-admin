# ------------------------------------------------------------------ clients
CLIENTS = [
    dict(name="wifi-aps", ipaddr="203.0.113.201", secret="S" * 20, require_ma="yes", limit_proxy_state="auto",
         nas_type="other", enabled=True),
    dict(name="sw-192-0-2-2", ipaddr="192.0.2.2", secret="T" * 20, require_ma="auto",
         limit_proxy_state="no", nas_type="cisco", enabled=True),
    dict(name="v6", ipaddr="fd00::/64", secret="U" * 20, require_ma="auto", limit_proxy_state="yes",
         nas_type="other", enabled=True),
    dict(name="off", ipaddr="10.1.1.1", secret="V" * 20, enabled=False),
]


def test_render_clients():
    t = unlang.render_clients([dict(c) for c in CLIENTS])
    assert t == unlang.render_clients([dict(c) for c in reversed(CLIENTS)])
    assert "client off" not in t
    names = re.findall(r"^client (\S+) \{$", t, re.M)
    assert names == sorted(names) == ["sw-192-0-2-2", "v6", "wifi-aps"]
    assert ("client wifi-aps {\n\tipv4addr = 203.0.113.201\n\tsecret = \"" + "S" * 20 + "\"\n"
            "\tshortname = wifi-aps\n\tnas_type = other\n\trequire_message_authenticator = yes\n"
            "\tlimit_proxy_state = auto\n}\n") in t
    assert "\tipv6addr = fd00::/64\n" in t
    # only whitelisted keys (what the root helper accepts)
    keys = set(re.findall(r"^\t(\w+) =", t, re.M))
    assert keys <= {"ipaddr", "ipv4addr", "ipv6addr", "secret", "shortname", "nas_type",
                    "require_message_authenticator", "limit_proxy_state"}


def test_render_clients_allows_legacy_short_secret_but_not_unsafe():
    t = unlang.render_clients([dict(name="old", ipaddr="10.0.0.1", secret="short", enabled=True)])
    assert 'secret = "short"' in t
    for bad in ('a"b', "a\\b", "a b", "a${x}", "", None):
        with pytest.raises(ValueError):
            unlang.render_clients([dict(name="old", ipaddr="10.0.0.1", secret=bad, enabled=True)])


def test_render_clients_errors():
    base = dict(name="a", ipaddr="10.0.0.1", secret="x" * 16, enabled=True)
    with pytest.raises(ValueError):
        unlang.render_clients([base, dict(base, ipaddr="10.0.0.2")])  # duplicate name
    with pytest.raises(ValueError):
        unlang.render_clients([base, dict(base, name="b")])  # duplicate address
    with pytest.raises(ValueError):
        unlang.render_clients([dict(base, require_ma="maybe")])
    with pytest.raises(ValueError):
        unlang.render_clients([dict(base, nas_type="x y")])
    with pytest.raises(ValueError):
        unlang.render_clients([dict(base, name="a}\nclient evil {")])
    assert unlang.render_clients([]).startswith("#\n#  Generated by radius-admin")
